"""Regenerate the pip package's standalone table calculations from the GUI notebook recipes."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "backend")]

from app.services import notebook_comparison, notebook_completeness, notebook_peptide
from app.services import notebook_ora
from app.services import notebook_phospho, notebook_qc, notebook_single, notebook_volcano, notebook_pathway
from app.services.notebook_source import extract_notebook_source, function_definition, merge_source, module_source


def render():
    sections = []

    def add(source, original, name):
        code = extract_notebook_source(source.code, (original,)).code
        sections.append(code.replace(f"def {original}(", f"def {name}("))

    for plot in ("coverage", "boxplot", "cv"):
        add(notebook_qc.qc_source(plot), "prepare_table", f"qc_{plot}_table")
    add(notebook_qc.qc_source("cv"), "qc_feature_cvs", "qc_feature_cvs")
    for plot in ("pearson", "venn"):
        add(notebook_comparison.comparison_source(plot), "prepare_table", f"{plot}_table")
    for plot, source in (("counts", notebook_phospho.count_source()),
                         ("coverage", notebook_phospho.coverage_source()),
                         ("distribution", notebook_phospho.category_source("distribution")),
                         ("sty", notebook_phospho.category_source("sty"))):
        add(source, "prepare_table", f"phospho_{plot}_table")
    for plot, source in (("boxplot", notebook_single.box_source()), ("lineplot", notebook_single.line_source()),
                         ("heatmap", notebook_single.heatmap_source())):
        name = f"single_protein_{plot}_table"
        add(source, "prepare_table", name if plot != "boxplot" else "_single_box_data")
    sections.append("def single_protein_boxplot_table(data, metadata, kind, protein, conditions, identifier='workflow', data_source='data'):\n"
                    "    return _single_box_data(data, metadata, kind, protein, conditions, identifier, data_source)[3]")
    for level in ("sample", "feature"):
        name = f"completeness_{level}_summary_table"
        add(notebook_completeness.completeness_source("missing-value"), name, name)
    add(notebook_peptide.coverage_source(), "summarize_peptide_coverage", "summarize_peptide_coverage")
    sections.append("def peptide_coverage_table(data, metadata):\n    return summarize_peptide_coverage(data, metadata)[0]")
    add(notebook_peptide.modification_source(), "peptide_modification_counts", "peptide_modification_counts")
    add(notebook_peptide.missed_cleavage_source(), "peptide_missed_cleavage_summary", "peptide_missed_cleavage_summary")
    add(notebook_pathway.pathway_source(), "prepare_matrix", "_pathway_matrix")
    add(notebook_ora.ora_source(), "export_term_rows", "_ora_export_rows")
    add(notebook_ora.gene_list_source(), "gene_list_terms_table", "gene_list_terms_table")
    sections.append("def ora_terms_table(result, request, direction):\n    return pd.DataFrame(_ora_export_rows(result, request, direction))")
    sections.append("def pathway_heatmap_table(data, metadata, database, **options):\n"
                    "    return _pathway_matrix(data, metadata, database, **options)[0]")
    volcano = notebook_volcano.volcano_source().code
    untested = function_definition(module_source("stats_tools.py"), "volcano_untested_table")
    sections.append(extract_notebook_source(merge_source(volcano, untested), ("volcano_untested_table",)).code)
    sections.append(extract_notebook_source(module_source("id_translation.py"), ("translate_id_table",)).code)
    collapse = module_source("external_functions.py")
    sections.append(extract_notebook_source(collapse, ("peptideCollapse",)).code)
    merged = merge_source(*sections)
    # Check that no two recipes gave a shared helper different meanings.
    extract_notebook_source(merged, ("qc_feature_cvs",))
    merged = "\n".join(line.rstrip() for line in merged.splitlines())
    return "# Peptide Collapse attribution and licensing are recorded in NOTICE.\n# Generated by tools/export_notebook_tables.py.\nfrom __future__ import annotations\n\n" + merged + "\n"


if __name__ == "__main__":
    (ROOT / "proteomicscopylot" / "notebook_tables.py").write_text(render(), encoding="utf-8")
